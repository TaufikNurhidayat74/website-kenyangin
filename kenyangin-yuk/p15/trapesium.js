// Definisi variabel (nilai dapat diubah sesuai kebutuhan)
const garisAtas = 8;   // Panjang garis atas (a)
const garisBawah = 12; // Panjang garis bawah (b)
const tinggi = 5;      // Tinggi trapesium (t)

// Rumus luas trapesium: 0.5 * (garisAtas + garisBawah) * tinggi
const luas = 0.5 * (garisAtas + garisBawah) * tinggi;

// Menampilkan hasil perhitungan ke konsol
console.log("--- Perhitungan Luas Trapesium ---");
console.log(`Garis Atas  : ${garisAtas}`);
console.log(`Garis Bawah : ${garisBawah}`);
console.log(`Tinggi      : ${tinggi}`);
console.log(`Luas        : ${luas}`);